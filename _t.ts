import 'dotenv/config';
import fs from 'fs';
import { v2 as c } from 'cloudinary';
import { PrismaClient } from '@prisma/client';
import { createMemberSessionToken, MEMBER_COOKIE_NAME } from './lib/memberSession';
import { fileThumbUrl } from './lib/file-url';
c.config({ cloud_name: process.env.CLOUDINARY_CLOUD_NAME, api_key: process.env.CLOUDINARY_API_KEY, api_secret: process.env.CLOUDINARY_API_SECRET, secure: true });
const p = new PrismaClient();
const B = 'http://localhost:3000';
(async () => {
  const src = 'attachments/1794285783238/추석특집크로스퍼즐24_기둥수학연구소.pdf';
  const buf = Buffer.from(await (await fetch(c.utils.private_download_url(src, '', { resource_type: 'raw', type: 'upload' } as any))).arrayBuffer());
  const up: any = await new Promise((res, rej) => c.uploader.upload_stream({ resource_type: 'image', public_id: 'attachments/test-pdf/소식지테스트' }, (e, x) => e ? rej(e) : res(x)).end(buf));
  const post = await p.post.create({ data: { code: 'com5', title: '[테스트] PDF 첨부 확인용', content: '<p>테스트</p>', isAdmin: true, files: { create: [{ url: up.secure_url, filename: '추석특집크로스퍼즐24_기둥수학연구소.pdf' }] } }, include: { files: true } });
  const fid = post.files[0].id;
  console.log('upload url', up.secure_url.replace(/^https:\/\/[^/]+/, ''));
  const thumb = fileThumbUrl(post.files, 640)!;
  const tr = await fetch(thumb); console.log('썸네일', tr.status, tr.headers.get('content-type'));
  const cookie = `${MEMBER_COOKIE_NAME}=${createMemberSessionToken({ idx: 0, id: 'local-test', name: '테스트' })}`;
  const list = await (await fetch(`${B}/board/com5`, { headers: { cookie } })).text();
  console.log('목록에 썸네일 img', list.includes('pg_1,q_auto:eco'));
  const detail = await (await fetch(`${B}/board/com5/${post.id}`, { headers: { cookie } })).text();
  console.log('상세: 미리보기', detail.includes('pg_1'), '/ 링크', detail.includes(`/api/files/${fid}`));
  const anon = await fetch(`${B}/api/files/${fid}`, { redirect: 'manual' }); console.log('다운로드(비로그인)', anon.status);
  const dl = await fetch(`${B}/api/files/${fid}`, { headers: { cookie }, redirect: 'manual' });
  console.log('다운로드(로그인)', dl.status);
  const pdf = await fetch(dl.headers.get('location')!); const b = Buffer.from(await pdf.arrayBuffer());
  console.log('최종 PDF', pdf.status, pdf.headers.get('content-type'), b.length, b.subarray(0, 5).toString());
  // 기존 raw PDF(법인 게시판) 다운로드
  const raw = await p.file.findFirst({ where: { url: { contains: '/raw/upload/' }, filename: { endsWith: '.pdf' }, post: { code: 'nt4' } }, select: { id: true } });
  const r1 = await fetch(`${B}/api/files/${raw!.id}`, { redirect: 'manual' }); const r2 = await fetch(r1.headers.get('location')!);
  console.log('기존 법인 PDF', r1.status, '→', r2.status, r2.headers.get('content-type'));
  fs.writeFileSync('_testids.json', JSON.stringify({ postId: post.id, publicId: up.public_id }));
  await p.$disconnect();
})().catch(e => { console.log('ERR', e); process.exit(1); });
