async function main() {
  const existing = await prisma.historyEntry.count()
  if (existing > 0) {
    console.log(`이미 연혁 ${existing}건이 등록되어 있어 시드를 건너뜁니다.`)
    return
  }

  await prisma.historyEntry.createMany({
    data: ENTRIES.map(([year, month, day, content], i) => ({ year, month, day, content, order: i })),
  })
  console.log(`연혁 ${ENTRIES.length}건을 등록했습니다.`)
}

main()
  .catch((e) => {
    console.error(e)
    process.exit(1)
  })
